/** Statuses that accept supplier claims. */
export const TRANSFER_CLAIMABLE_STATUSES = [
  TRANSFER_STATUS.OPEN_FOR_CLAIM,
  TRANSFER_STATUS.REOPENED_FOR_CLAIM,
  // legacy
  "open",
  "new",
  "seen",
];

export const TRANSFER_OPEN_STATUSES = TRANSFER_CLAIMABLE_STATUSES;

export const TRANSFER_CANCELLED_STATUSES = [
  TRANSFER_STATUS.CUSTOMER_CANCELLED,
  TRANSFER_STATUS.SUPPLIER_CANCELLED,
  TRANSFER_STATUS.ADMIN_CANCELLED,
  "cancelled",
];

const LEGACY_MAP = {
  open: TRANSFER_STATUS.OPEN_FOR_CLAIM,
  new: TRANSFER_STATUS.OPEN_FOR_CLAIM,
  seen: TRANSFER_STATUS.OPEN_FOR_CLAIM,
  claimed: TRANSFER_STATUS.CLAIMED,
  done: TRANSFER_STATUS.COMPLETED,
  cancelled: TRANSFER_STATUS.ADMIN_CANCELLED,
};

export function normalizeTransferStatus(status) {
  const raw = String(status || "").trim();
  if (!raw) return TRANSFER_STATUS.OPEN_FOR_CLAIM;
  if (LEGACY_MAP[raw]) return LEGACY_MAP[raw];
  if (Object.values(TRANSFER_STATUS).includes(raw)) return raw;
  return raw;
}

export function isTransferOpenStatus(status) {
  return TRANSFER_CLAIMABLE_STATUSES.includes(String(status || ""));
}

export function isTransferClaimable(status) {
  return isTransferOpenStatus(status);
}

