export function canTransitionTransferStatus(from, to) {
  const fromN = normalizeTransferStatus(from);
  const toN = normalizeTransferStatus(to);
  const allowed = TRANSFER_TRANSITIONS[fromN] || [];
  return allowed.includes(toN);
}

/**
 * @param {string} from
 * @param {string} to
 * @param {'customer'|'supplier'|'admin'|'system'} actor
 */
export function canActorTransition(from, to, actor) {
  if (!canTransitionTransferStatus(from, to)) return false;
  const toN = normalizeTransferStatus(to);
  const a = String(actor || "system");

  if (a === "system") return true;
  if (a === "admin") return true;

  if (a === "customer") {
    return [
      TRANSFER_STATUS.CUSTOMER_CANCELLED,
      TRANSFER_STATUS.OPEN_FOR_CLAIM,
    ].includes(toN);
  }

  if (a === "supplier") {
    return [
      TRANSFER_STATUS.CLAIMED,
      TRANSFER_STATUS.SUPPLIER_CANCELLED,
      TRANSFER_STATUS.DRIVER_ASSIGNED,
      TRANSFER_STATUS.DRIVER_EN_ROUTE,
      TRANSFER_STATUS.PASSENGER_PICKED_UP,
      TRANSFER_STATUS.COMPLETED,
    ].includes(toN);
  }

  return false;
}

export function defaultTransferCommissionPercent() {
  const n = Number(process.env.TRANSFER_COMMISSION_PERCENT || 15);
  return Number.isFinite(n) && n >= 0 && n <= 100 ? n : 15;
}

/** Default offer window before EXPIRED_UNCLAIMED (hours). */
export function defaultOfferTtlHours() {
  const n = Number(process.env.TRANSFER_OFFER_TTL_HOURS || 24);
  return Number.isFinite(n) && n > 0 ? n : 24;
}
